"""Measure authored alpha once at build time; never read canvas pixels in combat."""
import json,subprocess
from pathlib import Path
from PIL import Image
root=Path(__file__).resolve().parents[1]
code="import{SKILL_LOOKS}from'./rebirth/skill-looks.mjs';import{skillLookArtPath}from'./rebirth/skill-look-designs.mjs';console.log(JSON.stringify(SKILL_LOOKS.map(c=>({id:c.id,path:skillLookArtPath(c.id)}))))"
items=json.loads(subprocess.check_output(['node','--input-type=module','-e',code],cwd=root,text=True,encoding='utf8'))
result={};gains=[]
for item in items:
 image=Image.open(root/'rebirth'/item['path']).convert('RGBA');w,h=image.size;cw,ch=w//4,h//5;frames=[]
 for row in range(5):
  for col in range(4):
   alpha=image.getchannel('A').crop((col*cw,row*ch,(col+1)*cw,(row+1)*ch))
   box=alpha.point(lambda a:255 if a>12 else 0).getbbox()
   assert box,(item['id'],row,col)
   l,t,r,b=box;frames.append(dict(x=col*cw+l,y=row*ch+t,w=r-l,h=b-t))
   gains.append((cw/(r-l),ch/(b-t)))
 result[item['id']]=dict(asset=item['path'],width=w,height=h,frames=frames)
(root/'rebirth/skill-look-bounds-data.mjs').write_text('// Generated by scripts/build-skill-look-bounds.py; alpha > 12, 4 columns × 5 tiers.\nexport default '+json.dumps(result,separators=(',',':'))+';\n',encoding='utf8')
print('Measured',len(result),'themes /',len(gains),'components; maximum empty-margin correction',round(max(max(g) for g in gains),2),'x')
